#!/usr/bin/env python3
"""Zero-dependency OpenAPI → TypeScript type generator.

Reads the FastAPI app's live OpenAPI document (no server needed) and emits
TypeScript interfaces for every component schema into the frontend, so the
frontend never drifts from the backend contract by hand.

Usage (from repo root):
  backend\\.venv\\Scripts\\python.exe scripts\\openapi_tsgen.py            # write types
  backend\\.venv\\Scripts\\python.exe scripts\\openapi_tsgen.py --check   # verify freshness

No npm/Python dependency is introduced (project freeze rule). The generator
uses only the Python standard library.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend"
OUT = ROOT / "frontend" / "src" / "types" / "openapi.generated.ts"

TS_KEYWORDS = {
    "break", "case", "catch", "class", "const", "continue", "debugger", "default",
    "delete", "do", "else", "enum", "export", "extends", "false", "finally", "for",
    "function", "if", "import", "in", "instanceof", "new", "null", "return", "super",
    "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with",
}


def ts_type(schema: dict, indent: int, in_props: bool = False) -> str:
    """Map an OpenAPI JSON Schema fragment to a TypeScript type string."""
    pad = "  " * indent
    ref = schema.get("$ref")
    if ref:
        return ref.rsplit("/", 1)[-1]
    t = schema.get("type")
    if t == "array":
        items = ts_type(schema.get("items", {}), indent)
        return f"Array<{items}>"
    if t == "object" or "properties" in schema:
        props = schema.get("properties", {})
        required = set(schema.get("required", []))
        if not props:
            return "Record<string, unknown>"
        lines = ["{"]
        for key, sub in props.items():
            opt = "" if key in required else "?"
            safe_key = key if re.match(r"^[A-Za-z_$][A-Za-z0-9_$]*$", key) else json.dumps(key)
            lines.append(f"{pad}  {safe_key}{opt}: {ts_type(sub, indent + 1, True)};")
        lines.append(pad + "}")
        return "\n".join(lines)
    if t == "string":
        enum = schema.get("enum")
        if enum:
            return " | ".join(json.dumps(v) for v in enum)
        return "string"
    if t == "integer" or t == "number":
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    # anyOf / oneOf / allOf fallback
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(ts_type(sub, indent) for sub in schema[key])
    if "allOf" in schema:
        return " & ".join(ts_type(sub, indent) for sub in schema["allOf"])
    return "unknown"


def interface_name(name: str) -> str:
    """Sanitize a schema name into a valid exported TS identifier."""
    out = re.sub(r"[^A-Za-z0-9_$]", "_", name)
    if out[0].isdigit():
        out = "_" + out
    if out in TS_KEYWORDS:
        out = "_" + out
    return out


def generate(schemas: dict) -> str:
    lines = [
        "/* AUTO-GENERATED by scripts/openapi_tsgen.py — do not edit by hand. */",
        "/* Regenerate: backend\\.venv\\Scripts\\python.exe scripts\\openapi_tsgen.py */",
        "/* Reflects the live FastAPI OpenAPI component schemas at generation time. */",
        "",
    ]
    for name in sorted(schemas):
        lines.append(f"export interface {interface_name(name)} {ts_type(schemas[name], 0)}")
        lines.append("")
    return "\n".join(lines)


def load_schemas() -> dict:
    sys.path.insert(0, str(BACKEND))
    # Ensure project modules resolve from the backend package dir.
    if str(BACKEND) not in sys.path:
        sys.path.insert(0, str(BACKEND))
    from app.main import app

    return app.openapi().get("components", {}).get("schemas", {})


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if output is stale")
    args = parser.parse_args()

    schemas = load_schemas()
    body = generate(schemas)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    if args.check:
        if OUT.exists() and OUT.read_text(encoding="utf-8") == body:
            print(f"OK: {OUT} is fresh ({len(schemas)} schemas)")
            return 0
        print(f"STALE: {OUT} does not match the live OpenAPI ({len(schemas)} schemas)")
        return 1
    OUT.write_text(body, encoding="utf-8")
    print(f"Wrote {OUT} with {len(schemas)} schema interfaces")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

